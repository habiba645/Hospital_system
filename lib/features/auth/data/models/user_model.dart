import 'package:medidesk_app/features/auth/domain/entities/user_entity.dart';

class UserModel extends UserEntity {
  const UserModel({
    required super.id,
    required super.name,
    required super.email,
    required super.role,
    super.phone,
    super.avatarUrl,
  });

  factory UserModel.fromJson(Map<String, dynamic> json) {
    return UserModel(
      id: json['id']?.toString() ?? '',
      name: json['name'] as String? ?? '',
      email: json['email'] as String? ?? '',
      role: (json['role'] as String?)?.toLowerCase() == 'admin'
          ? UserRoleEntity.admin
          : UserRoleEntity.receptionist,
      phone: json['phone'] as String?,
      avatarUrl: json['avatar_url'] as String?,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'name': name,
      'email': email,
      'role': role == UserRoleEntity.admin ? 'admin' : 'receptionist',
      'phone': phone,
      'avatar_url': avatarUrl,
    };
  }
}
